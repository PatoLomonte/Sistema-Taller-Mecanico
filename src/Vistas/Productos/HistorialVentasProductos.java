    private void jbAnularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbAnularActionPerformed

            int fila = TablaVentas.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione una venta.");
            return;
        }

        int idVenta = Integer.parseInt(TablaVentas.getValueAt(fila, 0).toString());
        String fecha = TablaVentas.getValueAt(fila, 1).toString();
        String total = TablaVentas.getValueAt(fila, 2).toString();

        int opcion = JOptionPane.showConfirmDialog(
                null,
                "¿Desea anular esta venta?\n\n"
                + "Fecha: " + fecha + "\n"
                + "Total: $ " + total + "\n\n"
                + "Se devolverá el stock de los productos vendidos.",
                "Anular venta",
                JOptionPane.YES_NO_OPTION
        );

        if (opcion != JOptionPane.YES_OPTION) {
            return;
        }

        ventaProductoData.devolverStockDeVenta(idVenta);
        ventaProductoData.anularVentaProducto(idVenta);

        JOptionPane.showMessageDialog(null, "Venta anulada correctamente.");

        cargarVentas();
        
    }//GEN-LAST:event_jbAnularActionPerformed

