    private void armarCabeceraVentas() {

    modeloVentas.addColumn("ID");
    modeloVentas.addColumn("Fecha");
    modeloVentas.addColumn("Total");

    TablaVentas.setModel(modeloVentas);

    TablaVentas.getColumnModel().getColumn(0).setMinWidth(0);
    TablaVentas.getColumnModel().getColumn(0).setMaxWidth(0);
    TablaVentas.getColumnModel().getColumn(0).setWidth(0);
}
    
    
    
    
    private void armarCabeceraDetalle() {

    modeloDetalle.addColumn("Cantidad");
    modeloDetalle.addColumn("Producto");
    modeloDetalle.addColumn("Precio Unit.");
    modeloDetalle.addColumn("Total");

    TablaDetalle.setModel(modeloDetalle);
}
    
    
    
    
    private void cargarVentas() {

    modeloVentas.setRowCount(0);
    modeloDetalle.setRowCount(0);

    ArrayList<VentaProducto> ventas = ventaProductoData.listarVentasProducto();

    DateTimeFormatter formato = DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm");

    for (VentaProducto venta : ventas) {

        modeloVentas.addRow(new Object[]{
            venta.getIdVenta(),
            venta.getFecha().format(formato),
            venta.getTotal()
        });
    }
}
    
    
    
    
    
    private void cargarDetalleVenta(int idVenta) {

    modeloDetalle.setRowCount(0);

    ArrayList<DetalleVentaProducto> detalles = ventaProductoData.obtenerDetalleVentaProducto(idVenta);

    for (DetalleVentaProducto detalle : detalles) {

        String nombreProducto = "";

        if (detalle.getProducto() != null) {
            nombreProducto = detalle.getProducto().getNombre();
        }

        modeloDetalle.addRow(new Object[]{
            detalle.getCantidad(),
            nombreProducto,
            detalle.getPrecioUnitario(),
            detalle.getSubtotal()
        });
    }
}
    
     
    
    
    private void cargarDetalleVentaSeleccionada() {

    int fila = TablaVentas.getSelectedRow();

    if (fila == -1) {
        return;
    }

    int idVenta = Integer.parseInt(TablaVentas.getValueAt(fila, 0).toString());

    cargarDetalleVenta(idVenta);
}
    
    
    
