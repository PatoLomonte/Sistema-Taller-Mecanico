    private void jbModificarGastoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbModificarGastoActionPerformed

            int fila = TablaCompras.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione un gasto para modificar.");
            return;
        }

        int idGasto = (Integer) TablaCompras.getValueAt(fila, 0);

        Gasto gasto = gastoData.buscarGastoPorId(idGasto);

        if (gasto == null) {
            JOptionPane.showMessageDialog(null, "No se pudo cargar el gasto seleccionado.");
            return;
        }

        ModificarGasto modificar = new ModificarGasto(gasto);
        modificar.setVisible(true);

        this.dispose();

    }//GEN-LAST:event_jbModificarGastoActionPerformed

    private void jbAnularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbAnularActionPerformed

            int fila = TablaCompras.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione un gasto para anular.");
            return;
        }

        int idGasto = (Integer) TablaCompras.getValueAt(fila, 0);

        String fecha = TablaCompras.getValueAt(fila, 1).toString();
        String categoria = TablaCompras.getValueAt(fila, 2).toString();
        String descripcion = TablaCompras.getValueAt(fila, 3).toString();

        String montoTexto =
                TablaCompras.getValueAt(fila, 4).toString()
                .replace("$", "")
                .trim();

        int monto = Integer.parseInt(montoTexto);

        int opcion = JOptionPane.showConfirmDialog(
                null,
                "¿Está seguro que desea anular este gasto?\n\n"
                + "Fecha: " + fecha + "\n"
                + "Categoría: " + categoria + "\n"
                + "Descripción: " + descripcion + "\n"
                + "Monto: $" + monto,
                "Confirmar anulación",
                JOptionPane.YES_NO_OPTION
        );

        if (opcion != JOptionPane.YES_OPTION) {
            return;
        }

        gastoData.anularGasto(idGasto);

        cargarGastos();

    }//GEN-LAST:event_jbAnularActionPerformed

