    private int obtenerNumeroMes(String mes) {

    switch (mes) {

        case "Enero":
            return 1;

        case "Febrero":
            return 2;

        case "Marzo":
            return 3;

        case "Abril":
            return 4;

        case "Mayo":
            return 5;

        case "Junio":
            return 6;

        case "Julio":
            return 7;

        case "Agosto":
            return 8;

        case "Septiembre":
            return 9;

        case "Octubre":
            return 10;

        case "Noviembre":
            return 11;

        case "Diciembre":
            return 12;

        default:
            return 0;
    }
}
    
    
    
    
    private void cargarGastos() {

        modeloGastos.setRowCount(0);

        if (jcbMes.getSelectedItem() == null || jcbAnio.getSelectedItem() == null) {
            return;
        }

        String nombreMes = jcbMes.getSelectedItem().toString();
        String textoAnio = jcbAnio.getSelectedItem().toString();

        int mes;

        if (nombreMes.equals("Todos")) {
            mes = 0;
        } else {
            mes = obtenerNumeroMes(nombreMes);
        }

        int anio;

        if (textoAnio.equals("Todos")) {
            anio = 0;
        } else {
            anio = Integer.parseInt(textoAnio);
        }

        ArrayList<Gasto> gastos =
                gastoData.listarGastosFiltro(mes, anio);

        DateTimeFormatter formato =
                DateTimeFormatter.ofPattern("dd/MM/yyyy");

        int total = 0;

        for (Gasto gasto : gastos) {

            modeloGastos.addRow(new Object[]{
                gasto.getIdGasto(),
                gasto.getFecha().format(formato),
                gasto.getCategoria(),
                gasto.getDescripcion(),
                "$ " + gasto.getMonto(),
                gasto.getObservacion()
            });

            total += gasto.getMonto();
        }

        jtTotal.setText("$ " + total);
}
    
    
    
