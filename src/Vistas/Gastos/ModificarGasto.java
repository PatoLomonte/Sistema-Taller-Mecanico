    private void jbGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbGuardarActionPerformed

            try {

            String fechaTexto = jtFecha.getText().trim();
            String categoria = jcbCategoria.getSelectedItem().toString();
            String descripcion = jtDescripcion.getText().trim();
            String montoTexto = jtMonto.getText().trim();
            String observacion = jtObservacion.getText().trim();

            if (fechaTexto.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Ingrese la fecha.");
                return;
            }

            if (descripcion.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Ingrese una descripción.");
                return;
            }

            if (montoTexto.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Ingrese el monto.");
                return;
            }

            int monto = Integer.parseInt(montoTexto);

            if (monto <= 0) {
                JOptionPane.showMessageDialog(null, "El monto debe ser mayor a 0.");
                return;
            }

            DateTimeFormatter formato = DateTimeFormatter.ofPattern("dd/MM/yyyy");

            LocalDate fecha = LocalDate.parse(fechaTexto, formato);

            LocalDateTime fechaGasto = fecha.atStartOfDay();

            gastoActual.setFecha(fechaGasto);
            gastoActual.setCategoria(categoria);
            gastoActual.setDescripcion(descripcion);
            gastoActual.setMonto(monto);
            gastoActual.setObservacion(observacion);

            gastoData.modificarGasto(gastoActual);

            VerGastos ver = new VerGastos();
            ver.setVisible(true);

            this.dispose();

        } catch (NumberFormatException ex) {

            JOptionPane.showMessageDialog(null, "El monto debe ser un número válido.");

        } catch (DateTimeParseException ex) {

            JOptionPane.showMessageDialog(
                null,
                "La fecha debe tener el formato dd/MM/yyyy. Ejemplo: 08/07/2026"
            );
        }

    }//GEN-LAST:event_jbGuardarActionPerformed

