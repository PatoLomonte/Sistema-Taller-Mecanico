    private void cargarCategorias() {

    jcbCategoria.removeAllItems();

    jcbCategoria.addItem("Alquiler");
    jcbCategoria.addItem("Luz");
    jcbCategoria.addItem("Agua");
    jcbCategoria.addItem("Internet");
    jcbCategoria.addItem("Nafta");
    jcbCategoria.addItem("Herramientas");
    jcbCategoria.addItem("Insumos");
    jcbCategoria.addItem("Limpieza");
    jcbCategoria.addItem("Comida");
    jcbCategoria.addItem("Varios");
}
    
    
    
    
    private void cargarDatos() {

    DateTimeFormatter formato = DateTimeFormatter.ofPattern("dd/MM/yyyy");

    jtFecha.setText(gastoActual.getFecha().format(formato));

    jcbCategoria.setSelectedItem(gastoActual.getCategoria());

    jtDescripcion.setText(gastoActual.getDescripcion());
    jtMonto.setText(String.valueOf(gastoActual.getMonto()));
    jtObservacion.setText(gastoActual.getObservacion());
}
    
    
    
    
