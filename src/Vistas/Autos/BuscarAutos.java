    private void armarCabeceraAutos() {

    modeloAutos.addColumn("ID");
    modeloAutos.addColumn("Patente");
    modeloAutos.addColumn("Vehículo");
    modeloAutos.addColumn("Cliente");
    modeloAutos.addColumn("Teléfono");

    TablaAutos.setModel(modeloAutos);

    TablaAutos.getColumnModel().getColumn(0).setMinWidth(0);
    TablaAutos.getColumnModel().getColumn(0).setMaxWidth(0);
    TablaAutos.getColumnModel().getColumn(0).setWidth(0);
}
    
    
    
    
    private void buscarAutos() {

    modeloAutos.setRowCount(0);

    String patente = jtPatente.getText().trim();

    ArrayList<Auto> autos = autoData.buscarAutosPorPatente(patente);

    for (Auto auto : autos) {

        modeloAutos.addRow(new Object[]{
            auto.getIdAuto(),
            auto.getPatente(),
            auto.getVehiculo(),
            auto.getCliente().getNombre(),
            auto.getCliente().getTelefono()
        });
    }
}
    
    
    
    
    private void abrirGestionAutoSeleccionado() {

        int fila = TablaAutos.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione un auto.");
            return;
        }

        int idAuto = (Integer) TablaAutos.getValueAt(fila, 0);

        Auto auto = autoData.buscarAutoPorId(idAuto);

        if (auto == null) {
            JOptionPane.showMessageDialog(null, "No se pudo cargar el auto seleccionado.");
            return;
        }

        GestionAuto gestion = new GestionAuto(auto);
        gestion.setVisible(true);

        this.dispose();
}
    
    
    
    
    
