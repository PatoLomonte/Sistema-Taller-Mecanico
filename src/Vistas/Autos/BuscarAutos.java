    private void jbBajaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbBajaActionPerformed
        
            int fila = TablaAutos.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione un auto para dar de baja.");
            return;
        }

        int idAuto = (Integer) TablaAutos.getValueAt(fila, 0);

        Auto auto = autoData.buscarAutoPorId(idAuto);

        if (auto == null) {
            JOptionPane.showMessageDialog(null, "No se pudo encontrar el auto seleccionado.");
            return;
        }

        int opcion = JOptionPane.showConfirmDialog(
                null,
                "¿Está seguro que desea dar de baja este auto?\n\n"
                + "Patente: " + auto.getPatente() + "\n"
                + "Vehículo: " + auto.getVehiculo() + "\n"
                + "Cliente: " + auto.getCliente().getNombre() + "\n\n"
                + "Esta acción no borra el historial, solo oculta el auto del sistema.",
                "Confirmar baja",
                JOptionPane.YES_NO_OPTION
        );

        if (opcion != JOptionPane.YES_OPTION) {
            return;
        }

        autoData.darDeBajaAuto(idAuto);

        buscarAutos();
        
    }//GEN-LAST:event_jbBajaActionPerformed

