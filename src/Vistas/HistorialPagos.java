    private void armarCabeceraPagos() {

        modeloPagos.addColumn("ID");
        modeloPagos.addColumn("Fecha");
        modeloPagos.addColumn("Monto");
        modeloPagos.addColumn("Observación");

        TablaPagos.setModel(modeloPagos);

        TablaPagos.getColumnModel().getColumn(0).setMinWidth(0);
        TablaPagos.getColumnModel().getColumn(0).setMaxWidth(0);
        TablaPagos.getColumnModel().getColumn(0).setWidth(0);
    }

    
    
    
    private void cargarPagos() {

        modeloPagos.setRowCount(0);

        ArrayList<Pago> pagos =
            pagoData.listarPagosPorCasa(casaActual);

        DateTimeFormatter formato =
            DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm");

        for (Pago pago : pagos) {

            modeloPagos.addRow(new Object[]{
                pago.getIdPago(),
                pago.getFecha().format(formato),
                "$ " + pago.getMonto(),
                pago.getObservacion()
            });
        }
    }
    
    
