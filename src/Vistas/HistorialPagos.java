    private void jbAnularPagoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbAnularPagoActionPerformed

        int fila = TablaPagos.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione un pago para anular.");
            return;
        }

        int idPago = (Integer) TablaPagos.getValueAt(fila, 0);

        String fecha = TablaPagos.getValueAt(fila, 1).toString();

        String montoTexto = TablaPagos.getValueAt(fila, 2).toString()
                .replace("$", "")
                .trim();

        int monto = Integer.parseInt(montoTexto);

        String observacion = TablaPagos.getValueAt(fila, 3).toString();

        int opcion = JOptionPane.showConfirmDialog(
                null,
                "¿Está seguro que desea anular este pago?\n\n"
                + "Fecha: " + fecha + "\n"
                + "Monto: $" + monto + "\n"
                + "Observación: " + observacion + "\n\n"
                + "Este importe se volverá a sumar al saldo de la casa.",
                "Confirmar anulación",
                JOptionPane.YES_NO_OPTION
        );

        if (opcion != JOptionPane.YES_OPTION) {
            return;
        }

        pagoData.anularPago(idPago);

        casaData.sumarSaldo(casaActual.getIdCasa(), monto);

        JOptionPane.showMessageDialog(null, "Pago anulado correctamente.");

        Casa casaActualizada = casaData.buscarCasaPorId(casaActual.getIdCasa());

        GestionCasa gestioncasa = new GestionCasa(casaActualizada);
        gestioncasa.setVisible(true);

        this.dispose();

    }//GEN-LAST:event_jbAnularPagoActionPerformed

    

