    private void jbEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbEliminarActionPerformed
        
            int fila = TablaCasas.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione una casa para eliminar.");
            return;
        }

        int idCasa = (Integer) TablaCasas.getValueAt(fila, 0);

        Casa casa = casaData.buscarCasaPorId(idCasa);

        if (casa == null) {
            JOptionPane.showMessageDialog(null, "No se pudo encontrar la casa seleccionada.");
            return;
        }

        if (casa.getSaldo() > 0) {
            JOptionPane.showMessageDialog(
                null,
                "No se puede eliminar esta casa porque tiene saldo pendiente.\n\n"
                + "Saldo actual: $" + casa.getSaldo()
            );
            return;
        }

        int opcion = JOptionPane.showConfirmDialog(
            null,
            "¿Está seguro que desea eliminar la casa?\n\n"
            + "Casa: " + casa.getNombre() + "\n"
            + "Esta acción no borrará el historial, solo la ocultará del sistema.",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION
        );

        if (opcion != JOptionPane.YES_OPTION) {
            return;
        }

        casaData.desactivarCasa(idCasa);

        llenarTablaCasas();
        
    }//GEN-LAST:event_jbEliminarActionPerformed

