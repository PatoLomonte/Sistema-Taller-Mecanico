    private void abrirGestionCasaSeleccionada() {

    int fila = TablaCasas.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(null, "Seleccione una casa.");
        return;
    }

    int idCasa = (Integer) TablaCasas.getValueAt(fila, 0);

    Casa casa = casaData.buscarCasaPorId(idCasa);

    if (casa == null) {
        JOptionPane.showMessageDialog(null, "No se pudo cargar la casa seleccionada.");
        return;
    }

    GestionCasa gestion = new GestionCasa(casa);
    gestion.setVisible(true);

    this.dispose();
}
    
    
    
    
