    private void llenarTablaCasas() {

    modeloCasas.setRowCount(0);

    ArrayList<Casa> lista = casaData.listarCasas();

    for (Casa casa : lista) {
        modeloCasas.addRow(new Object[]{casa.getIdCasa(), casa.getNombre(), casa.getTelefono(), "$ " + casa.getSaldo()});
    }
}
    
    
    
    
    
    private void armarCabecera() {

    modeloCasas.addColumn("ID");
    modeloCasas.addColumn("Nombre");
    modeloCasas.addColumn("Teléfono");
    modeloCasas.addColumn("Saldo");

    TablaCasas.setModel(modeloCasas);

    TablaCasas.getColumnModel().getColumn(0).setMinWidth(0);
    TablaCasas.getColumnModel().getColumn(0).setMaxWidth(0);
    TablaCasas.getColumnModel().getColumn(0).setWidth(0);
}
    
    
    
    

